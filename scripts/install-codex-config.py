def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def validate_managed_leaf(path: Path, label: str) -> None:
    if is_linklike(path):
        raise ValueError(
            f"{label} must not be a symbolic link or junction: {path.as_posix()}"
        )
    if path.exists() and not path.is_file():
        raise ValueError(f"{label} must be a regular file: {path.as_posix()}")


def write_text_atomic(path: Path, content: str) -> None:
    validate_managed_leaf(path, "Managed output")
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = path.stat().st_mode & 0o777 if path.exists() else 0o644
    temp_path: Optional[Path] = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=path.parent,
            prefix=f".{path.name}.",
            suffix=".tmp",
            delete=False,
        ) as handle:
            temp_path = Path(handle.name)
            handle.write(content)
        os.chmod(temp_path, mode)
        os.replace(temp_path, path)
        temp_path = None
    finally:
        if temp_path is not None:
            temp_path.unlink(missing_ok=True)


