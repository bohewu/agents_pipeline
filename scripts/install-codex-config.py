def _scan_multiline_string_state(line: str, state: Optional[str]) -> Optional[str]:
    """Track TOML multiline strings so string contents are never parsed as syntax."""

    index = 0
    while index < len(line):
        if state is not None:
            delimiter = state
            found = line.find(delimiter, index)
            if found < 0:
                return state
            if delimiter == '"""':
                backslashes = 0
                cursor = found - 1
                while cursor >= 0 and line[cursor] == "\\":
                    backslashes += 1
                    cursor -= 1
                if backslashes % 2:
                    index = found + 1
                    continue
            state = None
            index = found + 3
            continue

        if line.startswith('"""', index):
            state = '"""'
            index += 3
            continue
        if line.startswith("'''", index):
            state = "'''"
            index += 3
            continue
        char = line[index]
        if char == "#":
            break
        if char == '"':
            index += 1
            while index < len(line):
                if line[index] == '"':
                    backslashes = 0
                    cursor = index - 1
                    while cursor >= 0 and line[cursor] == "\\":
                        backslashes += 1
                        cursor -= 1
                    if backslashes % 2 == 0:
                        index += 1
                        break
                index += 1
            continue
        if char == "'":
            closing = line.find("'", index + 1)
            index = len(line) if closing < 0 else closing + 1
            continue
        index += 1
    return state


def _syntax_line_flags(lines: Sequence[str]) -> List[bool]:
    state: Optional[str] = None
    flags: List[bool] = []
    for line in lines:
        flags.append(state is None)
        state = _scan_multiline_string_state(line, state)
    return flags


def _canonical_table_path(raw: str) -> str:
    """Canonicalize simple TOML dotted keys, including quoted agent names."""

    parts: List[str] = []
    index = 0
    while True:
        while index < len(raw) and raw[index].isspace():
            index += 1
        if index >= len(raw):
            return raw.strip()
        if raw[index] == '"':
            start = index
            index += 1
            escaped = False
            while index < len(raw):
                char = raw[index]
                if char == '"' and not escaped:
                    index += 1
                    break
                if char == "\\" and not escaped:
                    escaped = True
                else:
                    escaped = False
                index += 1
            else:
                return raw.strip()
            try:
                part = json.loads(raw[start:index])
            except (TypeError, ValueError, json.JSONDecodeError):
                return raw.strip()
        elif raw[index] == "'":
            closing = raw.find("'", index + 1)
            if closing < 0:
                return raw.strip()
            part = raw[index + 1 : closing]
            index = closing + 1
        else:
            match = BARE_KEY_RE.match(raw, index)
            if match is None:
                return raw.strip()
            part = match.group(0)
            index = match.end()
        if not isinstance(part, str):
            return raw.strip()
        parts.append(part)
        while index < len(raw) and raw[index].isspace():
            index += 1
        if index == len(raw):
            return ".".join(parts)
        if raw[index] != ".":
            return raw.strip()
        index += 1


def parse_blocks(text: str) -> List[Block]:
    blocks: List[Block] = []
    current_kind = "preamble"
    current_path: Optional[str] = None
    current_lines: List[str] = []

    multiline_state: Optional[str] = None
    for line in text.splitlines():
        syntax_line = multiline_state is None
        array_match = ARRAY_TABLE_RE.match(line) if syntax_line else None
        table_match = TABLE_RE.match(line) if syntax_line else None
        multiline_state = _scan_multiline_string_state(line, multiline_state)
        if array_match or table_match:
            if current_lines or current_kind != "preamble" or not blocks:
                blocks.append(Block(current_kind, current_path, current_lines))
            current_kind = "array" if array_match else "table"
            current_path = _canonical_table_path(
                (array_match or table_match).group(1).strip()
            )
            current_lines = [line]
            continue
        current_lines.append(line)

    if current_lines or current_kind != "preamble" or not blocks:
        blocks.append(Block(current_kind, current_path, current_lines))
    return blocks


def render_blocks(blocks: Sequence[Block]) -> str:
    rendered: List[str] = []
    for block in blocks:
        lines = list(block.lines)
        while lines and not lines[-1].strip():
            lines.pop()
        if not lines:
            continue
        rendered.append("\n".join(lines))
    if not rendered:
        return ""
    return "\n\n".join(rendered).rstrip() + "\n"


def validate_toml_text(text: str, label: str) -> None:
    if tomllib is None:
        raise RuntimeError("Codex installation requires Python 3.11 or newer.")
    if not text.strip():
        return
    try:
        tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        raise ValueError(f"{label} is not valid TOML: {exc}") from exc


def find_block_index(blocks: Sequence[Block], *, kind: str, path: str) -> Optional[int]:
    for idx, block in enumerate(blocks):
        if block.kind == kind and block.path == path:
            return idx
    return None


def insert_index_before_prefix(blocks: Sequence[Block], prefix: str) -> Optional[int]:
    for idx, block in enumerate(blocks):
        if (
            block.kind in {"table", "array"}
            and block.path
            and block.path.startswith(prefix)
        ):
            return idx
    return None


def ensure_root_table(blocks: List[Block], path: str) -> Block:
    existing_idx = find_block_index(blocks, kind="table", path=path)
    if existing_idx is not None:
        return blocks[existing_idx]

    child_idx = insert_index_before_prefix(blocks, path + ".")
    if child_idx is not None:
        insert_idx = child_idx
    elif blocks and blocks[0].kind == "preamble":
        insert_idx = 1
    else:
        insert_idx = len(blocks)

    block = Block("table", path, [f"[{path}]"])
    blocks.insert(insert_idx, block)
    return block


def upsert_assignment(block: Block, key: str, value: str) -> None:
    assign_re = re.compile(rf"^\s*{re.escape(key)}\s*=")
    new_line = f"{key} = {value}"
    output = [block.lines[0]]
    replaced = False

    syntax_flags = _syntax_line_flags(block.lines)
    for line, syntax_line in zip(block.lines[1:], syntax_flags[1:]):
        if syntax_line and assign_re.match(line) and not line.lstrip().startswith("#"):
            if not replaced:
                output.append(new_line)
                replaced = True
            continue
        output.append(line)

    if not replaced:
        while len(output) > 1 and not output[-1].strip():
            output.pop()
        output.append(new_line)

    block.lines = output


def remove_assignment_if_value(block: Block, key: str, value: str) -> bool:
    assign_re = re.compile(rf"^\s*{re.escape(key)}\s*=\s*{re.escape(value)}\s*(?:#.*)?$")
    output = [block.lines[0]]
    removed = False

    syntax_flags = _syntax_line_flags(block.lines)
    for line, syntax_line in zip(block.lines[1:], syntax_flags[1:]):
        if syntax_line and assign_re.match(line) and not line.lstrip().startswith("#"):
            removed = True
            continue
        output.append(line)

    block.lines = output
    return removed


def _dotted_root_pattern(root: str, key: Optional[str] = None) -> re.Pattern[str]:
    root_token = rf'(?:{re.escape(root)}|"{re.escape(root)}"|\'{re.escape(root)}\')'
    if key is None:
        return re.compile(rf"^\s*{root_token}\s*\.")
    key_token = rf'(?:{re.escape(key)}|"{re.escape(key)}"|\'{re.escape(key)}\')'
    return re.compile(rf"^\s*{root_token}\s*\.\s*{key_token}\s*=")


def has_dotted_root_assignment(block: Block, root: str) -> bool:
    pattern = _dotted_root_pattern(root)
    return any(
        syntax_line and pattern.match(line) and not line.lstrip().startswith("#")
        for line, syntax_line in zip(block.lines, _syntax_line_flags(block.lines))
    )


def upsert_dotted_root_assignment(
    block: Block, root: str, key: str, value: str
) -> None:
    pattern = _dotted_root_pattern(root, key)
    new_line = f"{root}.{key} = {value}"
    output: List[str] = []
    replaced = False
    for line, syntax_line in zip(block.lines, _syntax_line_flags(block.lines)):
        if (
            syntax_line
            and pattern.match(line)
            and not line.lstrip().startswith("#")
        ):
            if not replaced:
                output.append(new_line)
                replaced = True
            continue
        output.append(line)
    if not replaced:
        while output and not output[-1].strip():
            output.pop()
        output.append(new_line)
    block.lines = output


def remove_dotted_root_assignment_if_value(
    block: Block, root: str, key: str, value: str
) -> bool:
    prefix = _dotted_root_pattern(root, key).pattern.removesuffix("=")
    pattern = re.compile(rf"{prefix}=\s*{re.escape(value)}\s*(?:#.*)?$")
    output: List[str] = []
    removed = False
    for line, syntax_line in zip(block.lines, _syntax_line_flags(block.lines)):
        if syntax_line and pattern.match(line) and not line.lstrip().startswith("#"):
            removed = True
            continue
        output.append(line)
    block.lines = output
    return removed


