def parse_manifest(path: Path) -> Optional[Dict[str, object]]:
    validate_managed_leaf(path, "Codex installer manifest")
    if not path.exists():
        return None
    data = json.loads(read_text(path))
    if not isinstance(data, dict):
        raise ValueError(f"{path.as_posix()}: invalid manifest shape")

    raw_version = data.get("version", 0)
    if type(raw_version) is not int or not 0 <= raw_version <= MANIFEST_VERSION:
        raise ValueError(f"{path.as_posix()}: unsupported manifest version")
    raw_tool = data.get("tool")
    if raw_tool is not None and raw_tool != MANIFEST_TOOL:
        raise ValueError(f"{path.as_posix()}: unexpected manifest tool identity")
    if raw_version >= 2 and raw_tool != MANIFEST_TOOL:
        raise ValueError(f"{path.as_posix()}: missing manifest tool identity")
    if raw_version >= 2:
        declared_target = data.get("target_dir")
        if (
            not isinstance(declared_target, str)
            or Path(declared_target).expanduser().resolve() != path.parent.resolve()
        ):
            raise ValueError(f"{path.as_posix()}: manifest target does not match its location")
    if (
        raw_version == MANIFEST_VERSION
        and data.get("managed_support_root") != SUPPORT_TREE_DIRNAME
    ):
        raise ValueError(f"{path.as_posix()}: invalid managed support root")

    names = data.get("managed_agent_names")
    files = data.get("managed_agent_files")
    if not isinstance(names, list) or not isinstance(files, list):
        raise ValueError(f"{path.as_posix()}: invalid manifest shape")
    if not all(
        isinstance(name, str) and MANAGED_AGENT_NAME_RE.fullmatch(name)
        for name in names
    ):
        raise ValueError(f"{path.as_posix()}: invalid managed agent name")
    if len(set(names)) != len(names):
        raise ValueError(f"{path.as_posix()}: duplicate managed agent name")

    file_names: List[str] = []
    for file_path in files:
        if not isinstance(file_path, str):
            raise ValueError(f"{path.as_posix()}: invalid managed agent file")
        match = MANAGED_AGENT_FILE_RE.fullmatch(file_path)
        if match is None:
            raise ValueError(
                f"{path.as_posix()}: managed agent files must match "
                "agents/<name>.toml"
            )
        file_names.append(match.group(1))
    if len(set(files)) != len(files):
        raise ValueError(f"{path.as_posix()}: duplicate managed agent file")
    if set(names) != set(file_names):
        raise ValueError(
            f"{path.as_posix()}: managed agent names and files do not match"
        )

    return {
        "manifest_version": raw_version,
        "managed_agent_names": list(names),
        "managed_agent_files": list(files),
    }


def write_manifest(
    path: Path,
    *,
    agent_names: Sequence[str],
    agent_files: Sequence[str],
    profile: Optional[str],
    model_set: Optional[str],
    uniform_model: Optional[str],
    source_agents_dir: Path,
    target_dir: Path,
) -> None:
    mode = "default"
    if uniform_model:
        mode = "uniform"
    elif profile:
        mode = "profile"
    payload = {
        "tool": MANIFEST_TOOL,
        "version": MANIFEST_VERSION,
        "profile": profile or ("uniform" if uniform_model else None),
        "mode": mode,
        "model_set": model_set,
        "uniform_model": uniform_model,
        "target_dir": target_dir.resolve().as_posix(),
        "managed_support_root": SUPPORT_TREE_DIRNAME,
        "managed_agent_names": sorted(agent_names),
        "managed_agent_files": sorted(agent_files),
    }
    write_text_atomic(path, json.dumps(payload, indent=2, sort_keys=True) + "\n")


def is_generated_role_file(path: Path) -> bool:
    if is_linklike(path) or not path.exists() or not path.is_file():
        return False
    try:
        return GENERATED_ROLE_MARKER in read_text(path).splitlines()[:3]
    except OSError:
        return False


def validate_generated_role_ownership(path: Path) -> None:
    if not path.exists():
        return
    if not is_generated_role_file(path):
        raise ValueError(
            "Refusing to replace or remove a Codex role file without the generated "
            f"ownership marker: {path}"
        )


def infer_previous_managed(target_dir: Path) -> Dict[str, object]:
    manifest_path = target_dir / MANIFEST_FILENAME
    manifest = parse_manifest(manifest_path)
    if manifest is not None:
        version = manifest.get("manifest_version")
        if isinstance(version, int) and version < 2:
            files = [
                relative
                for relative in manifest["managed_agent_files"]
                if is_generated_role_file(target_dir / str(relative))
            ]
            return {
                "manifest_version": version,
                "managed_agent_names": [Path(relative).stem for relative in files],
                "managed_agent_files": files,
            }
        return manifest

    names: List[str] = []
    files: List[str] = []
    agents_dir = target_dir / "agents"
    if agents_dir.exists():
        for role_file in sorted(agents_dir.glob("*.toml")):
            if not is_generated_role_file(role_file):
                continue
            names.append(role_file.stem)
            files.append(role_file.relative_to(target_dir).as_posix())
    return {
        "manifest_version": None,
        "managed_agent_names": names,
        "managed_agent_files": files,
    }


def resolve_managed_agent_path(target_dir: Path, relative_path: str) -> Path:
    if MANAGED_AGENT_FILE_RE.fullmatch(relative_path) is None:
        raise ValueError(
            f"Unsafe managed agent path: {relative_path!r}; expected agents/<name>.toml"
        )
    resolved_target = target_dir.expanduser().resolve()
    lexical_path = resolved_target / relative_path
    expected_parent = resolved_target / "agents"
    if lexical_path.parent.resolve() != expected_parent:
        raise ValueError(
            f"Unsafe managed agent path escapes target directory: {relative_path!r}"
        )
    if is_linklike(lexical_path):
        raise ValueError(
            f"Managed agent path must not be a symbolic link or junction: {relative_path!r}"
        )
    if lexical_path.exists() and not lexical_path.is_file():
        raise ValueError(f"Managed agent path is not a file: {relative_path!r}")
    return lexical_path


def resolve_managed_tree_target(target_dir: Path, dirname: str) -> Path:
    lexical = (target_dir / dirname).expanduser()
    if is_linklike(lexical):
        raise ValueError(
            f"Managed support path must not be a symbolic link or junction: {dirname!r}"
        )
    resolved_target = target_dir.expanduser().resolve()
    expected = resolved_target / dirname
    resolved = lexical.resolve()
    if resolved != expected:
        raise ValueError(
            f"Unsafe managed support path escapes target directory: {dirname!r}"
        )
    return resolved


def is_legacy_support_tree_owned(path: Path) -> bool:
    return (
        path.is_dir()
        and not is_linklike(path)
        and all((path / marker).is_file() for marker in LEGACY_SUPPORT_TREE_MARKERS)
    )


def should_remove_legacy_support(
    previous_manifest: Dict[str, object],
    *,
    manifest_exists: bool,
    legacy_support_path: Path,
) -> bool:
    version = previous_manifest.get("manifest_version")
    return (
        manifest_exists
        and isinstance(version, int)
        and version < MANIFEST_VERSION
        and is_legacy_support_tree_owned(legacy_support_path)
    )


def build_export_command(
    export_script: Path,
    source_agents_dir: Path,
    modes_path: Path,
    catalog_path: Path,
    target_dir: Path,
    *,
    strict: bool,
    max_threads: int,
    max_depth: int,
    job_max_runtime_seconds: Optional[int],
    resolve_support_refs_to: Optional[Path],
    agent_profile: Optional[str] = None,
    model_set: Optional[str] = None,
    profile_dir: Optional[Path] = None,
    model_set_dir: Optional[Path] = None,
    uniform_model: Optional[str] = None,
) -> List[str]:
    command = [
        sys.executable,
        export_script.as_posix(),
        "--source-agents",
        source_agents_dir.as_posix(),
        "--modes-file",
        modes_path.as_posix(),
        "--target-dir",
        target_dir.as_posix(),
        "--catalog",
        catalog_path.as_posix(),
        "--max-threads",
        str(max_threads),
        "--max-depth",
        str(max_depth),
    ]
    if strict:
        command.append("--strict")
    if job_max_runtime_seconds is not None:
        command.extend(["--job-max-runtime-seconds", str(job_max_runtime_seconds)])
    if resolve_support_refs_to is not None:
        command.extend(
            ["--resolve-support-refs-to", resolve_support_refs_to.as_posix()]
        )
    if agent_profile is not None:
        command.extend(["--agent-profile", agent_profile])
    if model_set is not None:
        command.extend(["--model-set", model_set])
    if profile_dir is not None:
        command.extend(["--profile-dir", profile_dir.as_posix()])
    if model_set_dir is not None:
        command.extend(["--model-set-dir", model_set_dir.as_posix()])
    if uniform_model is not None:
        command.extend(["--uniform-model", uniform_model])
    return command


def resolve_temp_root(*, repo_root: Path, temp_dir: Optional[str]) -> Path:
    if temp_dir:
        return Path(temp_dir).expanduser()
    return repo_root / ".tmp"


def run_export(
    export_script: Path,
    source_agents_dir: Path,
    modes_path: Path,
    catalog_path: Path,
    *,
    strict: bool,
    max_threads: int,
    max_depth: int,
    job_max_runtime_seconds: Optional[int],
    temp_root: Path,
    resolve_support_refs_to: Optional[Path],
    agent_profile: Optional[str] = None,
    model_set: Optional[str] = None,
    profile_dir: Optional[Path] = None,
    model_set_dir: Optional[Path] = None,
    uniform_model: Optional[str] = None,
) -> Path:
    try:
        temp_root.mkdir(parents=True, exist_ok=True)
        temp_dir = Path(
            tempfile.mkdtemp(prefix="agents-pipeline-codex-", dir=temp_root)
        )
    except OSError as exc:
        raise RuntimeError(
            f"Unable to create temp dir under {temp_root.as_posix()}: {exc}"
        ) from exc
    command = build_export_command(
        export_script,
        source_agents_dir,
        modes_path,
        catalog_path,
        temp_dir,
        strict=strict,
        max_threads=max_threads,
        max_depth=max_depth,
        job_max_runtime_seconds=job_max_runtime_seconds,
        resolve_support_refs_to=resolve_support_refs_to,
        agent_profile=agent_profile,
        model_set=model_set,
        profile_dir=profile_dir,
        model_set_dir=model_set_dir,
        uniform_model=uniform_model,
    )
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        if result.stdout:
            sys.stderr.write(result.stdout)
        if result.stderr:
            sys.stderr.write(result.stderr)
        shutil.rmtree(temp_dir, ignore_errors=True)
        raise RuntimeError(
            f"Codex role export failed with exit code {result.returncode}."
        )
    return temp_dir


def extract_generated_agent_blocks(config_text: str) -> Dict[str, Block]:
    validate_toml_text(config_text, "Generated Codex config")
    blocks = parse_blocks(config_text)
    generated: Dict[str, Block] = {}
    for block in blocks:
        if (
            block.kind != "table"
            or not block.path
            or not block.path.startswith("agents.")
        ):
            continue
        if block.path == "agents":
            continue
        name = block.path[len("agents.") :]
        if "." in name:
            continue
        generated[name] = Block(block.kind, block.path, list(block.lines))
    return generated


def merge_config_text(
    existing_text: str,
    current_agent_blocks: Dict[str, Block],
    *,
    previous_agent_names: Sequence[str],
    max_threads: int,
    max_depth: int,
    job_max_runtime_seconds: Optional[int],
    manage_agent_limits: bool,
    remove_legacy_agent_limits: bool,
) -> str:
    validate_toml_text(existing_text, "Existing Codex config")
    blocks = parse_blocks(existing_text)
    managed_headers = {
        f"agents.{name}"
        for name in set(previous_agent_names) | set(current_agent_blocks)
    }
    blocks = [
        block
        for block in blocks
        if not (block.kind == "table" and block.path in managed_headers)
    ]
    if not blocks or blocks[0].kind != "preamble":
        blocks.insert(0, Block("preamble", None, []))
    preamble = blocks[0]

    features_idx = find_block_index(blocks, kind="table", path="features")
    if features_idx is None and has_dotted_root_assignment(preamble, "features"):
        upsert_dotted_root_assignment(preamble, "features", "multi_agent", "true")
    else:
        features_block = ensure_root_table(blocks, "features")
        upsert_assignment(features_block, "multi_agent", "true")

    agents_idx = find_block_index(blocks, kind="table", path="agents")
    use_dotted_agents = (
        agents_idx is None and has_dotted_root_assignment(preamble, "agents")
    )
    agents_block = None if use_dotted_agents else ensure_root_table(blocks, "agents")
    if manage_agent_limits:
        if use_dotted_agents:
            upsert_dotted_root_assignment(
                preamble, "agents", "max_threads", str(max_threads)
            )
            upsert_dotted_root_assignment(
                preamble, "agents", "max_depth", str(max_depth)
            )
        else:
            assert agents_block is not None
            upsert_assignment(agents_block, "max_threads", str(max_threads))
            upsert_assignment(agents_block, "max_depth", str(max_depth))
    elif remove_legacy_agent_limits:
        if use_dotted_agents:
            remove_dotted_root_assignment_if_value(
                preamble, "agents", "max_threads", str(DEFAULT_MAX_THREADS)
            )
            remove_dotted_root_assignment_if_value(
                preamble, "agents", "max_depth", str(DEFAULT_MAX_DEPTH)
            )
        else:
            assert agents_block is not None
            remove_assignment_if_value(
                agents_block, "max_threads", str(DEFAULT_MAX_THREADS)
            )
            remove_assignment_if_value(
                agents_block, "max_depth", str(DEFAULT_MAX_DEPTH)
            )
    if job_max_runtime_seconds is not None:
        if use_dotted_agents:
            upsert_dotted_root_assignment(
                preamble,
                "agents",
                "job_max_runtime_seconds",
                str(job_max_runtime_seconds),
            )
        else:
            assert agents_block is not None
            upsert_assignment(
                agents_block,
                "job_max_runtime_seconds",
                str(job_max_runtime_seconds),
            )

    for name in sorted(current_agent_blocks):
        block = current_agent_blocks[name]
        blocks.append(Block(block.kind, block.path, list(block.lines)))

    merged = render_blocks(blocks)
    validate_toml_text(merged, "Merged Codex config")
    return merged


def collect_generated_role_files(temp_dir: Path) -> Dict[str, str]:
    generated: Dict[str, str] = {}
    for role_file in sorted((temp_dir / "agents").glob("*.toml")):
        generated[role_file.relative_to(temp_dir).as_posix()] = read_text(role_file)
    return generated


def remove_file_if_present(path: Path, *, stop_path: Path) -> bool:
    if not path.exists() or not path.is_file():
        return False
    path.unlink()
    parent = path.parent
    while (
        parent != stop_path
        and parent.exists()
        and parent.is_dir()
        and not any(parent.iterdir())
    ):
        parent.rmdir()
        parent = parent.parent
    return True


def sync_support_tree(
    source_root: Path, target_root: Path, *, dry_run: bool = False
) -> None:
    if not SUPPORT_SYNC_SCRIPT.is_file():
        raise RuntimeError(
            f"Neutral support sync helper not found: {SUPPORT_SYNC_SCRIPT.as_posix()}"
        )
    command = [
        sys.executable,
        SUPPORT_SYNC_SCRIPT.as_posix(),
        "--source-root",
        source_root.as_posix(),
        "--target-root",
        target_root.as_posix(),
    ]
    if dry_run:
        command.append("--dry-run")
    result = subprocess.run(
        command,
        text=True,
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        raise RuntimeError(
            "Neutral support tree synchronization failed"
            + (f": {detail}" if detail else "")
        )


def seed_builtin_project_profile_caches(asset_root: Path, global_target: Path) -> None:
    helper = asset_root / "scripts" / "codex-project-profile.py"
    profile_dir = asset_root / DEFAULT_PROFILE_DIR
    model_set_dir = asset_root / DEFAULT_MODEL_SET_DIR
    if not helper.is_file():
        raise RuntimeError(f"Codex project profile helper not found: {helper.as_posix()}")
    profile_names = sorted(path.stem for path in profile_dir.glob("*.json"))
    model_set_names = sorted(path.stem for path in model_set_dir.glob("*.json"))
    if not profile_names or not model_set_names:
        raise RuntimeError("Built-in Codex profiles or model sets are missing.")
    for profile_name in profile_names:
        for model_set_name in model_set_names:
            result = subprocess.run(
                [
                    sys.executable,
                    helper.as_posix(),
                    "cache",
                    "--global-target",
                    global_target.as_posix(),
                    "--asset-root",
                    asset_root.as_posix(),
                    "--profile",
                    profile_name,
                    "--model-set",
                    model_set_name,
                ],
                capture_output=True,
                text=True,
                check=False,
            )
            if result.returncode != 0:
                detail = result.stderr.strip() or result.stdout.strip()
                raise RuntimeError(
                    "Unable to seed Codex project profile cache "
                    f"{profile_name}/{model_set_name}: {detail}"
                )


