def _markdown_marker_indices(lines: Sequence[str], marker: str) -> List[int]:
    indexes: List[int] = []
    fence_char: Optional[str] = None
    fence_length = 0
    for index, line in enumerate(lines):
        leading_spaces = len(line) - len(line.lstrip(" "))
        candidate = line[leading_spaces:] if leading_spaces <= 3 else ""
        if fence_char is not None:
            run = len(candidate) - len(candidate.lstrip(fence_char))
            if run >= fence_length and not candidate[run:].strip():
                fence_char = None
                fence_length = 0
            continue
        if candidate.startswith("```") or candidate.startswith("~~~"):
            char = candidate[0]
            run = len(candidate) - len(candidate.lstrip(char))
            fence_char = char
            fence_length = run
            continue
        if leading_spaces >= 4 or line.startswith("\t"):
            continue
        if line.strip() == marker:
            indexes.append(index)
    return indexes


def merge_agents_text(existing_text: str, managed_block: str, *, heading: str) -> str:
    normalized = existing_text.replace("\r\n", "\n")
    start_token = WORKSPACE_AGENTS_MANAGED_START
    end_token = WORKSPACE_AGENTS_MANAGED_END
    managed = managed_block.rstrip()

    lines = normalized.split("\n")
    start_indices = _markdown_marker_indices(lines, start_token)
    end_indices = _markdown_marker_indices(lines, end_token)
    if len(start_indices) != len(end_indices) or len(start_indices) > 1:
        raise ValueError("Managed AGENTS block has malformed or duplicate markers.")
    start_idx = start_indices[0] if start_indices else None
    end_idx = end_indices[0] if end_indices else None
    if start_idx is not None and (end_idx is None or end_idx <= start_idx):
        raise ValueError("Managed AGENTS block markers are out of order.")

    if start_idx is not None and end_idx is not None and start_idx < end_idx:
        before = "\n".join(lines[:start_idx]).rstrip()
        after = "\n".join(lines[end_idx + 1 :]).strip()
        parts = [part for part in (before, managed, after) if part]
        return "\n\n".join(parts).rstrip() + "\n"

    cleaned = normalized.strip()
    if not cleaned:
        return f"{heading}\n\n{managed}\n"
    return cleaned.rstrip() + "\n\n" + managed + "\n"


